package io.github.jimbozoomer.jugcraft.nuclear;

/**
 * The three nuclear pipes. The coolant pipe and the steam line join the unit's equipment (the unit forms through them);
 * the circulating water conduit carries the condenser's cooling water and draws it straight from water it touches.
 * Same ids and order as PIPES in tools/nuclear.py.
 */
public enum PipeKind {
	COOLANT("reactor_coolant_pipe", 10),
	STEAM("insulated_steam_line", 10),
	WATER("circulating_water_conduit", 14),
	/** The generator's isolated phase bus: joins a turbine-generator to its main transformer (no need to touch). */
	BUS("isolated_phase_bus", 12);

	public final String id;
	/** Pipe thickness in pixels (the models are generated by tools/nuclear.py). */
	public final int size;

	PipeKind(String id, int size) {
		this.id = id;
		this.size = size;
	}
}
