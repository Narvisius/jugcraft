	/**
	 * The space the finished tower (the foundation and tiers 1-9) takes, relative to the core: its box (x east, z south)
	 * and, for a plan of it, each column's top ({@code tops[(z - minZ) * width + x - minX]}, or Integer.MIN_VALUE where the
	 * tower has nothing). The core's placement warning (TowerPlacement, client/TowerPlaceScreen) states it.
	 */
	public record Extent(int minX, int maxX, int minY, int maxY, int minZ, int maxZ, int[] tops) {
		/** East to west (blocks). */
		public int width() {
			return maxX - minX + 1;
		}

		/** North to south (blocks). */
		public int length() {
			return maxZ - minZ + 1;
		}

		/** Bottom to top (blocks). */
		public int height() {
			return maxY - minY + 1;
		}

		/** The top of the column at (x, z) relative to the core, or Integer.MIN_VALUE where the tower has none. */
		public int top(int x, int z) {
			if (x < minX || x > maxX || z < minZ || z > maxZ) {
				return Integer.MIN_VALUE;
			}
			return tops[(z - minZ) * width() + x - minX];
		}
	}

	private @org.jspecify.annotations.Nullable Extent extent;

	/** The finished tower's space (worked out once). */
	public synchronized Extent extent() {
		if (extent == null) {
			List<Tier> steps = new java.util.ArrayList<>();
			if (foundation != null) {
				steps.add(foundation);
			}
			steps.addAll(tiers);
			int minX = Integer.MAX_VALUE, maxX = Integer.MIN_VALUE, minY = Integer.MAX_VALUE, maxY = Integer.MIN_VALUE;
			int minZ = Integer.MAX_VALUE, maxZ = Integer.MIN_VALUE;
			for (Tier step : steps) {
				for (int[] b : step.place) {
					minX = Math.min(minX, b[0]);
					maxX = Math.max(maxX, b[0]);
					minY = Math.min(minY, b[1]);
					maxY = Math.max(maxY, b[1]);
					minZ = Math.min(minZ, b[2]);
					maxZ = Math.max(maxZ, b[2]);
				}
			}
			if (minX > maxX) {
				extent = new Extent(0, 0, 0, 0, 0, 0, new int[] {Integer.MIN_VALUE});
				return extent;
			}
			int width = maxX - minX + 1;
			int[] tops = new int[width * (maxZ - minZ + 1)];
			java.util.Arrays.fill(tops, Integer.MIN_VALUE);
			for (Tier step : steps) {
				for (int[] b : step.place) {
					int i = (b[2] - minZ) * width + b[0] - minX;
					tops[i] = Math.max(tops[i], b[1]);
				}
			}
			extent = new Extent(minX, maxX, minY, maxY, minZ, maxZ, tops);
		}
		return extent;
	}

	public static boolean supportedLayout(int version) {
		return version >= LEGACY_LAYOUT && version <= CURRENT_LAYOUT;
	}

	/** Tier {@code number} (1 to 9). */
	public Tier tier(int number) {
		return tiers.get(number - 1);
	}

	/** Drones a tower of {@code tier} holds (0 before tier 1). */
	public int capacity(int tier) {
		return tier <= 0 ? 0 : tier(Math.min(TIERS, tier)).capacity;
	}

	public BlockState state(int paletteIndex) {
		return palette.get(paletteIndex);
	}

	private final Map<Tier, Map<net.minecraft.world.item.Item, Integer>> costs = new java.util.IdentityHashMap<>();

	/**
	 * What {@code step} costs: every item its blocks are placed from (a fitting placed whole from one item counts once),
	 * most needed first. Worked out from the design the first time it is asked for.
	 */
	public synchronized Map<net.minecraft.world.item.Item, Integer> cost(Tier step) {
		return costs.computeIfAbsent(step, s -> TowerCosts.of(this, s));
	}

	private static TowerData load(String name) {
		String path = "/data/jugcraft/drone_tower/" + name + ".json.gz";
		try (InputStream raw = TowerData.class.getResourceAsStream(path)) {
			if (raw == null) {
				throw new IllegalStateException("missing " + path);
			}
			JsonObject root = JsonParser.parseReader(new InputStreamReader(new GZIPInputStream(raw), StandardCharsets.UTF_8)).getAsJsonObject();
			List<BlockState> palette = new ArrayList<>();
			for (JsonElement entry : root.getAsJsonArray("palette")) {
				palette.add(parse(entry.getAsString()));
			}
			List<Tier> tiers = new ArrayList<>();
			for (JsonElement element : root.getAsJsonArray("tiers")) {
				tiers.add(tier(element.getAsJsonObject()));
			}
			Tier foundation = root.has("foundation") ? tier(root.getAsJsonObject("foundation")) : null;
			List<Pad> pads = new ArrayList<>();
			for (JsonElement p : root.getAsJsonArray("pads")) {
				JsonObject o = p.getAsJsonObject();
				pads.add(new Pad(o.get("x").getAsInt(), o.get("z").getAsInt(), o.get("ex").getAsDouble(), o.get("ez").getAsDouble()));
			}
			TowerData data = new TowerData(palette, foundation, tiers, pads, root.get("plinth").getAsInt(), point(root, "terminal"),
					root.has("platform") ? point(root, "platform") : null, root.has("packager") ? point(root, "packager") : null);
			if (root.has("crew")) {
				data.crew = io.github.jimbozoomer.jugcraft.tower.crew.CrewPost.list(root.getAsJsonArray("crew"));
			}
			if (root.has("night_lights")) {
				JsonArray lamps = root.getAsJsonArray("night_lights");
				data.nightLights = new int[lamps.size()][];
				for (int i = 0; i < lamps.size(); i++) {
					JsonArray l = lamps.get(i).getAsJsonArray();
					data.nightLights[i] = new int[] {l.get(0).getAsInt(), l.get(1).getAsInt(), l.get(2).getAsInt(),
							TowerLightBlock.Mode.of(l.get(3).getAsString()).ordinal()};
				}
			}
			return data;
		} catch (Exception e) {
			Jugcraft.LOGGER.error("Could not read the Drone Tower data", e);
			throw new IllegalStateException("Drone Tower data unreadable", e);
		}
	}

	private static int[] point(JsonObject root, String name) {
		JsonArray a = root.getAsJsonArray(name);
		return new int[] {a.get(0).getAsInt(), a.get(1).getAsInt(), a.get(2).getAsInt()};
	}

	private static Tier tier(JsonObject t) {
		List<Dock> docks = new ArrayList<>();
		for (JsonElement d : t.getAsJsonArray("docks")) {
			JsonObject o = d.getAsJsonObject();
			docks.add(new Dock(o.get("tier").getAsInt(), DroneSize.valueOf(o.get("size").getAsString().toUpperCase(Locale.ROOT)),
					o.get("x").getAsDouble(), o.get("y").getAsDouble(), o.get("z").getAsDouble(), o.get("ex").getAsDouble(),
					o.get("ez").getAsDouble(), o.has("door") ? ints1(o.getAsJsonArray("door")) : null));
		}
		List<Pickup> pickups = new ArrayList<>();
		for (JsonElement p : t.getAsJsonArray("pickups")) {
			JsonObject o = p.getAsJsonObject();
			pickups.add(new Pickup(o.get("tier").getAsInt(), o.get("x").getAsInt(), o.get("y").getAsInt(), o.get("z").getAsInt()));
		}
		return new Tier(t.get("tier").getAsInt(), t.get("name").getAsString(), t.get("top").getAsInt(), ints(t.getAsJsonArray("place")),
				ints(t.getAsJsonArray("clear")), t.has("air") ? ints(t.getAsJsonArray("air")) : new int[0][], docks, pickups, t.get("capacity").getAsInt());
	}

	private static BlockState parse(String state) {
		try {
			return BlockStateParser.parseForBlock(BuiltInRegistries.BLOCK, state, false).blockState();
		} catch (Exception e) {
			Jugcraft.LOGGER.error("Drone Tower data: unknown block state {}", state);
			return Blocks.AIR.defaultBlockState();
		}
	}

	private static int[][] ints(JsonArray array) {
		int[][] out = new int[array.size()][];
		for (int i = 0; i < out.length; i++) {
			JsonArray row = array.get(i).getAsJsonArray();
			out[i] = new int[row.size()];
			for (int j = 0; j < out[i].length; j++) {
				out[i][j] = row.get(j).getAsInt();
			}
		}
		return out;
	}

	private static long tileKey(int[] b) {
		return b[1] * 1_000_000L + (Math.floorDiv(b[0], TILE) + 500) * 1000L + (Math.floorDiv(b[2], TILE) + 500);
	}

	/**
	 * Groups a tier's blocks and cells to clear into tiles of up to {@link #TILE}x{@link #TILE} in one layer,
	 * bottom layers first. A cell to clear with no block in its tile gets a clear-only tile.
	 */
	private static List<Tile> tiles(int[][] place, int[][] air) {
		Map<Long, List<Integer>> groups = new LinkedHashMap<>();
		Map<Long, List<Integer>> clears = new LinkedHashMap<>();
		for (int i = 0; i < place.length; i++) {
			groups.computeIfAbsent(tileKey(place[i]), k -> new ArrayList<>()).add(i);
		}
		for (int i = 0; i < air.length; i++) {
			long key = tileKey(air[i]);
			groups.computeIfAbsent(key, k -> new ArrayList<>());
			clears.computeIfAbsent(key, k -> new ArrayList<>()).add(i);
		}
		List<Tile> tiles = new ArrayList<>();
		for (Map.Entry<Long, List<Integer>> group : groups.entrySet()) {
			int[] blocks = group.getValue().stream().mapToInt(Integer::intValue).toArray();
			int[] cells = clears.getOrDefault(group.getKey(), List.of()).stream().mapToInt(Integer::intValue).toArray();
			int[] first = blocks.length > 0 ? place[blocks[0]] : air[cells[0]];
			tiles.add(new Tile(first[0], first[1], first[2], blocks, cells));
		}
		tiles.sort((a, b) -> Integer.compare(a.y(), b.y()));
		return tiles;
	}

	private static int[] ints1(JsonArray array) {
		int[] out = new int[array.size()];
		for (int i = 0; i < out.length; i++) {
			out[i] = array.get(i).getAsInt();
		}
		return out;
	}
