def columns(ch):
    """The glyph as 5 column bitmasks (bit 0 the top row)."""
    rows = G.get(ch.upper(), G['?'])
    return [sum(1 << r for r in range(7) if rows[r][c] == '#') for c in range(5)]


def java():
    """The table as client/TickerRail's static block has it (one glyph(...) line a character)."""
    lines = []
    for ch in G:
        lit = {"\u00b7": "'\\u00B7'", "'": "'\\''"}.get(ch, "'" + ch + "'")
        lines.append("\t\tglyph(%s, %s);" % (lit, ", ".join(str(c) for c in columns(ch))))
    return "\n".join(lines)


if __name__ == '__main__':
    for k, v in G.items():
        assert len(v) == 7 and all(len(r) == 5 for r in v), k
    print(len(G), 'glyphs ok')
    print(java())
